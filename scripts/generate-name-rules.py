#!/usr/bin/env python3
"""Builds the name-rule data migration from supabase/name-rules/*.txt.

    python3 scripts/generate-name-rules.py [migration file name]

Default output: supabase/migrations/000039_name_rules_data.sql (already
deployed; don't regenerate it). After editing the .txt files, run this with a
NEW migration name (e.g. 000045_name_rules_update.sql). A new migration
replaces the three rule tables with the lists as they are now, so removals
take effect too (private.name_exceptions, managed by hand, is left alone).
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = ROOT / 'supabase' / 'name-rules'
DEFAULT = '000039_name_rules_data.sql'
OUT_NAME = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
OUT = ROOT / 'supabase' / 'migrations' / OUT_NAME
# The first data load only inserts; every later one is a full replacement.
REPLACE = OUT_NAME != DEFAULT

RESERVED = {
    'staff.txt': 'staff',
    'game_industry.txt': 'game_industry',
    'creators.txt': 'creator',
    'celebrities.txt': 'celebrity',
    'politicians.txt': 'politician',
    'companies.txt': 'company',
}


def lines(name: str) -> list[str]:
    out = []
    for raw in (RULES / name).read_text(encoding='utf-8').splitlines():
        line = raw.strip()
        if line and not line.startswith('#'):
            out.append(line)
    return out


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def values(rows: list[tuple[str, ...]]) -> str:
    return ',\n  '.join('(' + ', '.join(q(v) for v in row) + ')' for row in rows)


def main() -> None:
    reserved = [(label, cat) for file, cat in RESERVED.items() for label in lines(file)]
    badwords = []
    for line in lines('badwords.txt'):
        word, match = line.rsplit(None, 1)
        if match not in ('anywhere', 'whole'):
            raise SystemExit(f'badwords.txt: "{line}" must end in anywhere or whole')
        badwords.append((word, match))
    allowed = [(w,) for w in lines('allowed_words.txt')]

    replace_sql = (
        """
-- Full replacement: rows removed from the lists are removed here too.
delete from private.name_blocklist;
delete from private.name_badwords;
delete from private.name_allowed_words;
"""
        if REPLACE
        else ''
    )
    sql = f"""-- =============================================================================
-- gamer_cred — name rules data (generated by scripts/generate-name-rules.py
-- from supabase/name-rules/*.txt — edit those, not this file)
--
-- {len(reserved)} reserved names, {len(badwords)} blocked words, {len(allowed)} allowed everyday words.
-- =============================================================================
{replace_sql}
insert into private.name_blocklist (name_key, label, category)
select distinct on (private.name_key(v.label)) private.name_key(v.label), v.label, v.category
  from (values
  {values(reserved)}
  ) as v (label, category)
 where private.name_key(v.label) <> ''
on conflict (name_key) do nothing;

insert into private.name_badwords (word_key, word, match)
select distinct on (private.name_fold(v.word)) private.name_fold(v.word), v.word, v.match
  from (values
  {values(badwords)}
  ) as v (word, match)
on conflict (word_key) do nothing;

insert into private.name_allowed_words (word_key, word)
select distinct on (private.name_fold(v.word)) private.name_fold(v.word), v.word
  from (values
  {values(allowed)}
  ) as v (word)
on conflict (word_key) do nothing;
"""
    OUT.write_text(sql, encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}: {len(reserved)} reserved, {len(badwords)} words, {len(allowed)} allowed')


if __name__ == '__main__':
    main()
